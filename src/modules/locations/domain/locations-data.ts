export function getLocationBySlug(slug: string): LocationCard | undefined {
  const norm = slug.trim().toLowerCase();
  return locationCards.find((loc) => loc.slug.toLowerCase() === norm);
}

export function getLocationByCode(code: string): LocationCard | undefined {
  const norm = code.trim().toLowerCase();
  return locationCards.find((loc) => loc.code.toLowerCase() === norm);
}

export function getLocationByRouteSegment(segment: string): LocationCard | undefined {
  const norm = segment.trim().toLowerCase();
  return locationCards.find((loc) => loc.slug.toLowerCase() === norm || loc.code.toLowerCase() === norm);
}

export function getLocationsByMarket(marketCode: string): LocationCard[] {
  if (marketCode === 'all') return locationCards;
  return locationCards.filter((loc) => loc.marketCode.toUpperCase() === marketCode.toUpperCase());
}

export function getLocationsByCity(cityCode: string): LocationCard[] {
  const norm = cityCode.trim().toLowerCase();
  return locationCards.filter((loc) => loc.cityCode.toLowerCase() === norm);
}
