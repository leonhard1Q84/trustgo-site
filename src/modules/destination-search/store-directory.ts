export function isStoreEligible(store: StoreLocationSnapshot): boolean {
  return store.enabled && store.officialWebsiteEnabled && store.rentalSearchEnabled;
}

export function findStoresWithinRadius(
  point: Wgs84Point,
  maxRadiusKm = 15,
  marketCode?: string
): PoiStoreMatch[] {
  return storeDirectory
    .filter((store) => isStoreEligible(store))
    .filter((store) => !marketCode || store.marketCode === marketCode)
    .map((store) => {
      const distanceKm = calculateDistanceKm(
        point.latitude,
        point.longitude,
        store.point.latitude,
        store.point.longitude
      );
      return {
        ...store,
        distanceKm,
      };
    })
    .filter((store) => store.distanceKm <= maxRadiusKm)
    .sort((a, b) => a.distanceKm - b.distanceKm);
}

export function calculateServiceLocationCount(
  point: Wgs84Point,
  maxRadiusKm = 15,
  marketCode?: string
): number {
  return findStoresWithinRadius(point, maxRadiusKm, marketCode).length;
}

export function getNearestStore(point: Wgs84Point, marketCode?: string): PoiStoreMatch | undefined {
  const stores = findStoresWithinRadius(point, 120, marketCode);
  return stores[0];
}

export function getStoreByCode(code: string): StoreLocationSnapshot | undefined {
  const normalized = code.trim().toLowerCase();
  return storeDirectory.find((store) => store.storeCode.toLowerCase() === normalized);
}
